"""User model for authentication."""

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Column,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import INET, JSONB
from sqlalchemy.orm import relationship, validates

from app.core.schema_types import normalize_email
from app.db.base import Base


class User(Base):
    __tablename__ = "users"
    __table_args__ = (
        Index("idx_users_party_id", "party_id"),
        # One ACTIVE login per party. Partial so a deactivated duplicate from
        # the repoint migration keeps its party_id as history (ADR 0003).
        Index(
            "uq_users_one_active_per_party",
            "party_id",
            unique=True,
            postgresql_where="is_active",
        ),
        Index("idx_users_is_active", "is_active"),
        # The column is unique already; this is the same invariant for the
        # normalised form, so a mixed-case duplicate cannot be inserted around
        # the application's normalisation (#191). Declared here so an
        # autogenerated revision does not propose dropping it.
        Index("uq_users_email_lower", text("lower(btrim(email))"), unique=True),
        Index("idx_users_reset_token", "reset_token", postgresql_where="reset_token IS NOT NULL"),
        Index(
            "idx_users_verification_token",
            "verification_token",
            postgresql_where="verification_token IS NOT NULL",
        ),
    )

    id = Column(Integer, primary_key=True, autoincrement=True)
    party_id = Column(
        BigInteger,
        ForeignKey("party.id", ondelete="CASCADE", name="users_party_id_fkey"),
        nullable=False,
    )
    email = Column(String(255), unique=True, nullable=False)
    # Nullable: SSO-only users (Google/Apple) have no password. The password login
    # path rejects a user whose hash is NULL.
    password_hash = Column(String(255))
    email_verified = Column(Boolean, default=False)
    email_verified_at = Column(DateTime(timezone=True))
    last_login_at = Column(DateTime(timezone=True))
    last_login_ip = Column(INET)
    reset_token = Column(String(255))
    reset_token_expires_at = Column(DateTime(timezone=True))
    verification_token = Column(String(255))
    verification_token_expires_at = Column(DateTime(timezone=True))
    is_active = Column(Boolean, default=True)
    # A session token issued before this instant is refused, whatever its own
    # expiry says. Set when the password is reset, so the sessions a stolen or
    # shared password opened die with it — a JWT is otherwise valid until it
    # expires and `/auth/refresh` lets an active one slide forever.
    sessions_valid_from = Column(DateTime(timezone=True))
    is_locked = Column(Boolean, default=False)
    locked_at = Column(DateTime(timezone=True))
    locked_reason = Column(Text)
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )

    # Relationships
    party = relationship("Party")
    # No FK between users and persons any more; both reference party, and the
    # join goes through it. viewonly: the link is written by setting party_id.
    person = relationship(
        "Person",
        primaryjoin="User.party_id == foreign(Person.party_id)",
        uselist=False,
        viewonly=True,
    )
    identities = relationship(
        "UserIdentity", back_populates="user", cascade="all, delete-orphan"
    )
    role_assignments = relationship(
        "UserRoleAssignment",
        back_populates="user",
        cascade="all, delete-orphan",
        foreign_keys="UserRoleAssignment.user_id",
    )
    # selectin, not lazy: authorization resolves on every request and a lazy load
    # here raises once the request's session is gone.
    roles = relationship(
        "Role",
        secondary="user_roles",
        primaryjoin="User.id == UserRoleAssignment.user_id",
        secondaryjoin="Role.id == UserRoleAssignment.role_id",
        viewonly=True,
        lazy="selectin",
    )

    @validates("email")
    def _normalise_email(self, _key, value):
        """Store the address the way every lookup spells it.

        The request schemas normalise on the way in, so the API can only ever
        match a stripped, lower-cased value. Anything writing this column
        without going through a schema — `app.cli.seed`, which builds addresses
        from its arguments and from SEED_EMAIL_DOMAIN — would otherwise create
        a row no spelling reaches: the capital is stored, and the login form
        normalises what it sends (#191).

        Here rather than at those call sites because the call sites are the
        part that keeps being missed. Validators do not fire when the ORM loads
        a row, so this normalises writes only and leaves existing values to the
        migration.
        """
        return normalize_email(value)


class Role(Base):
    __tablename__ = "roles"
    __table_args__ = (Index("idx_roles_slug", "slug"),)

    id = Column(Integer, primary_key=True, autoincrement=True)
    slug = Column(String(50), unique=True, nullable=False)
    name = Column(String(100), nullable=False)
    description = Column(Text)
    is_system = Column(Boolean, nullable=False, default=False, server_default="false")
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )

    permissions = relationship(
        "RolePermission",
        back_populates="role",
        cascade="all, delete-orphan",
        lazy="selectin",
    )

    @property
    def permission_keys(self) -> set[str]:
        return {p.permission_key for p in self.permissions}


class RolePermission(Base):
    __tablename__ = "role_permissions"
    __table_args__ = (Index("idx_role_permissions_role", "role_id"),)

    role_id = Column(
        Integer, ForeignKey("roles.id", ondelete="CASCADE"), primary_key=True
    )
    permission_key = Column(String(64), primary_key=True)

    role = relationship("Role", back_populates="permissions")


class UserRoleAssignment(Base):
    __tablename__ = "user_roles"
    __table_args__ = (Index("idx_user_roles_user", "user_id"),)

    user_id = Column(
        Integer, ForeignKey("users.id", ondelete="CASCADE"), primary_key=True
    )
    # RESTRICT, not CASCADE: deleting a role that is still assigned must fail at
    # the database, so an "assign" racing a "delete" cannot orphan the assignment.
    role_id = Column(
        Integer, ForeignKey("roles.id", ondelete="RESTRICT"), primary_key=True
    )
    assigned_at = Column(DateTime(timezone=True), server_default=func.now())
    assigned_by = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"))

    user = relationship("User", foreign_keys=[user_id], back_populates="role_assignments")
    role = relationship("Role")


class UserIdentity(Base):
    """A external provider account (Google, Apple) linked to a memship user.

    One user can have several identities plus a password, so signing in with
    Google and later with Apple on the same verified email resolves to the same
    account instead of creating a duplicate.
    """

    __tablename__ = "user_identities"
    __table_args__ = (
        CheckConstraint("provider IN ('google', 'apple')", name="valid_auth_provider"),
        UniqueConstraint("provider", "provider_subject", name="uq_provider_subject"),
        Index("idx_user_identities_user_id", "user_id"),
    )

    id = Column(Integer, primary_key=True, autoincrement=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    provider = Column(String(20), nullable=False)
    # The provider's stable subject id — never the email, which can change.
    provider_subject = Column(String(255), nullable=False)
    email = Column(String(255))
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    user = relationship("User", back_populates="identities")

    @validates("email")
    def _normalise_email(self, _key, value):
        """Same rule as ``User.email`` — see the validator there (#191)."""
        return normalize_email(value)
